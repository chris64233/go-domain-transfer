// Package domaintransfer 实现域名所有权 / 注册商转移流程。
//
// 该包提供以下能力：
//   - 域名所有者签发与域名、目标注册商、有效期绑定的一次性授权码（仅存摘要）；
//   - 在同一原子边界内消费授权码、锁定域名并发起转移，外部转移号保证幂等；
//   - 原注册商在决定期限内批准 / 拒绝，超期由策略自动批准；
//   - 人工决定、所有者取消、超时推进在并发下只会有一个操作落入终态；
//   - 批准在同一事务内切换所有权与注册商信息并生成且仅生成一条 outbox 事件；
//   - 完整的审计历史与状态查询，且明文授权码不出现在持久化内容、日志或错误中。
